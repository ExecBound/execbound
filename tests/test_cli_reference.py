"""The command-line reference is the commands' own parsers, written out.

`docs/CLI_REFERENCE.md` is generated by `scripts/cli_reference.py` from `execbound.cli` and the
monitoring commands, so a command, an argument, a choice or a default that changes without the
page being written again fails here. The arguments that still carry no help text are counted,
and the count may only fall: a new argument comes with its help.
"""

import argparse
from datetime import timedelta
from pathlib import Path

import pytest

from execbound.cli import build_parser
from execbound.cli_reference import render
from execbound.command_help import COMMON_HELP
from execbound.monitoring.commands import build_parser as monitoring_parser

# Reads a document, so it carries `docs` and `pytest -m docs` selects it (#748).
pytestmark = pytest.mark.docs

PAGE = Path(__file__).resolve().parents[1] / "docs" / "CLI_REFERENCE.md"

# Arguments with no help of their own and none shared: 167 on October 5, 2026, 130 on
# October 7 once the owner administration and bundle commands were described, and 91 on
# October 9 once the executor key, connector registry, context source and signal source
# commands were, and 90 on October 18 once `process --deliver-local` was. Lower it as help is
# written; never raise it.
WITHOUT_HELP = 90


def _arguments() -> list[tuple[str, argparse.Action]]:
    found = []
    for parser in (build_parser()[0], monitoring_parser()):
        commands = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
        for name, command in commands.choices.items():
            for action in command._actions:
                if not isinstance(action, argparse._HelpAction):
                    found.append((name, action))
    return found


def test_the_committed_reference_is_what_the_parsers_describe() -> None:
    assert PAGE.read_text(encoding="utf-8") == render(), "run scripts/cli_reference.py"


def test_every_command_of_both_entry_points_has_a_section() -> None:
    page = PAGE.read_text(encoding="utf-8")
    for program, parser in (
        ("execbound", build_parser()[0]),
        ("python -m execbound.monitoring.commands", monitoring_parser()),
    ):
        commands = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
        for name in commands.choices:
            assert f"### `{program} {name}`" in page, name


def test_the_shared_help_reaches_every_command_that_takes_the_argument() -> None:
    for command, action in _arguments():
        name = action.option_strings[-1] if action.option_strings else None
        if name in COMMON_HELP:
            assert action.help, (command, name)


def test_arguments_without_help_only_ever_get_fewer() -> None:
    bare = sorted(
        f"{command} {action.option_strings[-1] if action.option_strings else action.dest}"
        for command, action in _arguments()
        if not action.help
    )
    assert len(bare) <= WITHOUT_HELP, f"{len(bare)} arguments without help: {bare}"


def _help(command: str, option: str) -> str:
    for name, action in _arguments():
        if name == command and option in action.option_strings:
            return action.help or ""
    raise AssertionError(f"{command} takes no {option}")


def test_the_bounds_a_help_text_states_are_the_ones_the_command_enforces() -> None:
    """Help is prose no test can hold to the code, except for its numbers: each bound a help
    text quotes is the constant the command refuses by, so the two cannot drift apart."""
    from execbound import administration, passwords, provisioning, spaces
    from execbound.policy import preview

    hour = timedelta(hours=1)
    mebibyte = 1024 * 1024
    # Two shapes are a pattern rather than a constant, so the bound is read from the pattern
    # itself: the longest value it accepts, and the one length an Ed25519 key may have.
    hex_widths = [n for n in range(1, 129) if administration._PUBLIC_KEY.fullmatch("a" * n)]
    label_lengths = [n for n in range(1, 257) if provisioning._SIGNAL_LABEL.fullmatch("a" * n)]
    assert len(hex_widths) == 1 and label_lengths == list(range(1, len(label_lengths) + 1))
    signal_hours = (
        f"{provisioning.MIN_SIGNAL_LIFETIME // hour} to {provisioning.MAX_SIGNAL_LIFETIME // hour}"
    )
    stated = {
        ("executor-key-register", "--public-key"): f"Ed25519 as {hex_widths[0]} hex characters",
        ("executor-key-rotate", "--public-key"): f"Ed25519 as {hex_widths[0]} hex characters",
        ("mapping-create", "--mapping-version"): (
            f"1 to {administration.MAX_VERSION_LENGTH} characters"
        ),
        ("resource-create", "--version"): f"1 to {administration.MAX_VERSION_LENGTH} characters",
        ("resource-create", "--alias-days"): f"1 to {administration.MAX_ALIAS_DAYS}",
        ("context-import", "--manifest"): (
            f"at most {provisioning.MAX_MANIFEST_BYTES // mebibyte} MiB"
        ),
        ("signal-source-create", "--label"): f"1 to {label_lengths[-1]} characters",
        ("signal-source-create", "--hours"): signal_hours,
        ("signal-source-rotate", "--hours"): signal_hours,
        ("signal-source-rotate", "--grace-seconds"): (
            f"0 to {provisioning.MAX_SIGNAL_GRACE_SECONDS}"
        ),
        ("credential-issue", "--lifetime-hours"): (
            f"at most {administration.MAX_CREDENTIAL_LIFETIME // hour}"
        ),
        ("person-invite", "--lifetime-hours"): (
            f"between {passwords.MIN_RESET_LIFETIME // hour} and "
            f"{passwords.MAX_RESET_LIFETIME // hour}"
        ),
        ("group-create", "--name"): f"1 to {administration.MAX_GROUP_NAME_LENGTH} characters",
        ("space-create", "--name"): f"1 to {spaces.MAX_NAME_LENGTH} characters",
        ("space-rename", "--name"): f"1 to {spaces.MAX_NAME_LENGTH} characters",
        ("group-assign", "--principal"): (f"at most {administration.MAX_GROUP_MEMBERSHIPS} groups"),
        ("bundle-preview", "--window-hours"): f"at most {preview.MAX_WINDOW // hour}",
    }
    for (command, option), bound in stated.items():
        assert bound in _help(command, option), (command, option, bound)


def test_the_fact_values_a_help_text_lists_are_the_contract_domains() -> None:
    """`resource-create` checks its optional facts against the contract domains rather than
    argparse choices, so the values each fact's help lists are held to those domains here.
    Every contract declaring a fact must give it one domain, or one help text could not
    describe it."""
    from execbound.contracts import PRODUCTION_CATALOG, Column, IntegerDomain, StringDomain

    domains: dict[str, set[object]] = {}
    for version in PRODUCTION_CATALOG.versions:
        for spec in PRODUCTION_CATALOG.contract(version).facts:
            if spec.source_kind == "inventory" and isinstance(spec.storage, Column):
                domains.setdefault(spec.name, set()).add(spec.domain)

    def domain(name: str) -> object:
        [only] = domains[name]
        return only

    def one_of(name: str) -> str:
        values = domain(name)
        assert isinstance(values, StringDomain), name
        *rest, last = sorted(values.values)
        return f"one of {', '.join(rest)} or {last}"

    criticality = domain("criticality")
    assert isinstance(criticality, IntegerDomain)
    listed = {
        "--role": one_of("role"),
        "--privilege-class": one_of("privilege_class"),
        "--environment": one_of("environment"),
        "--criticality": f"{criticality.minimum} to {criticality.maximum}",
    }
    for option, values in listed.items():
        assert values in _help("resource-create", option), (option, values)
