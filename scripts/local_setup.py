# One definition of a worker's database name, shared with the suite's own fixtures, so
# the names this script creates and the names the tests connect to cannot drift apart.
from execbound.connection import worker_database

ROOT = Path(__file__).resolve().parents[1]
# CI overrides the loopback port so its database never collides with a developer's.
PORT = int(os.environ.get("POSTGRES_PORT", "55439"))
OWNER = "execbound_owner"
RUNTIME = "execbound_app"
LOCAL_HOSTS = {"127.0.0.1", "localhost", "::1"}
DATABASES = ("execbound", "execbound_test")
# pytest-xdist gives each worker its own test database, because the suite truncates every
# table between tests. `--test-workers N` provisions `execbound_test_gw0` to `gw(N-1)`
# beside the single one, which an undistributed run keeps using.
URLS = {
    "DATABASE_URL": (RUNTIME, "execbound", "EXECBOUND_APP_PASSWORD"),
    "MIGRATION_DATABASE_URL": (OWNER, "execbound", "POSTGRES_PASSWORD"),
    "TEST_DATABASE_URL": (RUNTIME, "execbound_test", "EXECBOUND_APP_PASSWORD"),
    "TEST_MIGRATION_DATABASE_URL": (OWNER, "execbound_test", "POSTGRES_PASSWORD"),
}


class SetupError(Exception):
    """An actionable failure whose message contains no credentials."""


# A failed `docker compose up` prints this much of what Compose wrote: enough for the
# daemon's own reason and the steps before it, not so much that it buries the reason.
COMPOSE_TAIL_LINES = 20
REDACTED = "[redacted]"


def redact(text: str, hidden: Iterable[str]) -> str:
    """`text` with every character of every occurrence of each `hidden` value replaced.

    Occurrences can overlap, and a URL can hold a password, so the characters to hide are
    marked first and each unbroken run of them becomes one `[redacted]`. Replacing value by
    value instead would leave the part of one value that another's replacement split off.
    """
    covered = [False] * len(text)
    for value in {value for value in hidden if value}:
        start = text.find(value)
        while start != -1:
            covered[start : start + len(value)] = [True] * len(value)
            start = text.find(value, start + 1)
    pieces: list[str] = []
    for index, character in enumerate(text):
        if not covered[index]:
            pieces.append(character)
        elif index == 0 or not covered[index - 1]:
            pieces.append(REDACTED)
    return "".join(pieces)


def write_exclusive(path: Path, contents: str) -> bool:
    """Publish a fully written, private file without replacing an existing file."""
    descriptor, temporary = tempfile.mkstemp(prefix=f"{path.name}.", dir=path.parent)
    temporary_path = Path(temporary)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(contents)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary_path, 0o600)
        try:
            # Linking within one filesystem atomically publishes the complete file.
            # Unlike replace/rename, it cannot overwrite another setup's credentials.
            os.link(temporary_path, path)
        except FileExistsError:
            return False
        return True
    finally:
        temporary_path.unlink(missing_ok=True)


def ensure_environment() -> dict[str, str]:
    env_path = ROOT / ".env"
    if not env_path.exists():
        passwords = {
            "POSTGRES_PASSWORD": secrets.token_urlsafe(32),
            "EXECBOUND_APP_PASSWORD": secrets.token_urlsafe(32),
        }
        values = dict(passwords)
        for key, (username, database, password_key) in URLS.items():
            values[key] = URL.create(
                "postgresql+psycopg",
                username=username,
                password=passwords[password_key],
                host="127.0.0.1",
                port=PORT,
                database=database,
            ).render_as_string(hide_password=False)
        contents = "# Local credentials generated by scripts/local_setup.py. Keep private.\n"
        contents += "".join(f"{key}={value}\n" for key, value in values.items())
        if write_exclusive(env_path, contents):
            print("Created local .env credentials.")

    values: dict[str, str] = {}
    for line in env_path.read_text(encoding="utf-8").splitlines():
        entry = line.strip()
        if not entry or entry.startswith("#"):
            continue
        key, separator, value = entry.partition("=")
        if not separator or key.strip() in values:
            raise SetupError("The local .env has a malformed or duplicate entry.")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
            value = value[1:-1]
        values[key.strip()] = value

    required = {*URLS, "POSTGRES_PASSWORD", "EXECBOUND_APP_PASSWORD"}
    if required - values.keys():
        raise SetupError(
            "The existing .env is missing required local setup keys; see .env.example."
        )
    for key in ("POSTGRES_PASSWORD", "EXECBOUND_APP_PASSWORD"):
        if (
            len(values[key]) < 32
            or values[key].startswith("REPLACE_WITH_")
            or any(character.isspace() for character in values[key])
        ):
            raise SetupError(f"{key} must be a strong password of at least 32 nonspace characters.")
    if secrets.compare_digest(values["POSTGRES_PASSWORD"], values["EXECBOUND_APP_PASSWORD"]):
        raise SetupError("Owner and runtime passwords must be different.")

    for key, (username, database, password_key) in URLS.items():
        try:
            parsed = make_url(values[key])
            matches = (
                parsed.drivername == "postgresql+psycopg"
                and parsed.host in LOCAL_HOSTS
                and parsed.port == PORT
                and parsed.username == username
                and parsed.database == database
                and parsed.password == values[password_key]
                and not parsed.query
            )
        except (ArgumentError, ValueError, TypeError):
            matches = False
        if not matches:
            raise SetupError(
                f"Refusing {key}: local setup requires its expected user/database, "
                f"a loopback host, port {PORT}, matching password, and no URL query options."
            )
    return values


def run_program(arguments: list[str], *, timeout: int = 90) -> subprocess.CompletedProcess[str]:
    options: dict[str, Any] = {}
    if os.name == "nt":
        options["creationflags"] = subprocess.CREATE_NO_WINDOW
    # Never inherit libpq service/host overrides or Compose overrides from another project.
    child_environment = {
        key: value
        for key, value in os.environ.items()
        if not key.startswith("PG")
        and not key.startswith("COMPOSE_")
        and key
        not in {
            *URLS,
            "POSTGRES_PASSWORD",
            "EXECBOUND_APP_PASSWORD",
            "DOCKER_HOST",
            "DOCKER_CONTEXT",
        }
    }
    try:
        # Background postgres processes can inherit pipe handles on Windows.
        # File capture waits only for the command, never for descendant pipe EOF.
        with tempfile.TemporaryFile(mode="w+", encoding="utf-8") as output:
            result = subprocess.run(
                arguments,
                cwd=ROOT,
                env=child_environment,
                stdin=subprocess.DEVNULL,
                stdout=output,
                stderr=output,
                timeout=timeout,
                check=False,
                **options,
            )
            output.seek(0)
            return subprocess.CompletedProcess(arguments, result.returncode, output.read(), "")
    except FileNotFoundError as error:
        raise SetupError(
            "A required executable is missing. Install Docker or provide --postgres-bin."
        ) from error
    except subprocess.TimeoutExpired as error:
        raise SetupError("A local database command exceeded its startup time limit.") from error


def start_docker(values: Mapping[str, str], project: str | None = None) -> None:
    """Start the Compose database. `values` is the `.env` Compose reads, every value of which
    is hidden from the output a failed start prints."""
    # Own the parent before Docker creates its bind-mount child as root on Linux.
    (ROOT / "local-data").mkdir(mode=0o700, exist_ok=True)
    context = run_program(["docker", "context", "inspect"])
    try:
        endpoint = json.loads(context.stdout)[0]["Endpoints"]["docker"]["Host"]
    except (json.JSONDecodeError, KeyError, IndexError, TypeError) as error:
        raise SetupError("Cannot verify the current Docker context is local.") from error
    if (
        context.returncode
        or not isinstance(endpoint, str)
        or not endpoint.startswith(("npipe://", "unix://"))
    ):
        raise SetupError("Local setup requires a local Docker socket; remote contexts are refused.")
    print("Starting local PostgreSQL with Docker Compose.")
    # An explicit project keeps a CI database apart from a developer's stack on the
    # same host; COMPOSE_* variables are deliberately not inherited (see run_program).
    result = run_program(
        [
            "docker",
            "compose",
            *(["-p", project] if project else []),
            "--env-file",
            str(ROOT / ".env"),
            "-f",
            str(ROOT / "compose.yaml"),
            "up",
            "-d",
            "db",
        ],
        timeout=180,
    )
    if result.returncode:
        # Compose reads `.env`, so its output can quote any value there; every one is hidden,
        # whatever its key, before any line of it is printed.
        output = redact(result.stdout, values.values())
        lines = [line for line in output.splitlines() if line.strip()][-COMPOSE_TAIL_LINES:]
        if not lines:
            raise SetupError(
                "Docker Compose startup failed and printed nothing. "
                "Check Docker's local service status."
            )
        raise SetupError(
            "Docker Compose startup failed. Check Docker's local service status. "
            f"What Compose wrote, at most its last {COMPOSE_TAIL_LINES} lines, every .env "
            f"value shown as {REDACTED}:\n" + "\n".join(f"  {line}" for line in lines)
        )


def start_native(binary_directory: Path, values: dict[str, str]) -> None:
    binary_directory = binary_directory.resolve()
    suffix = ".exe" if os.name == "nt" else ""
    initdb = binary_directory / f"initdb{suffix}"
    pg_ctl = binary_directory / f"pg_ctl{suffix}"
    if not initdb.is_file() or not pg_ctl.is_file():
        raise SetupError("--postgres-bin must contain PostgreSQL 17 initdb and pg_ctl executables.")
    version = run_program([str(initdb), "--version"])
    if version.returncode or "(PostgreSQL) 17." not in version.stdout:
        raise SetupError("The native local setup requires PostgreSQL major version 17.")

    local_directory = ROOT / "local-data"
    local_directory.mkdir(exist_ok=True)
    data_directory = local_directory / "postgres"
    version_file = data_directory / "PG_VERSION"
    if not version_file.exists():
        if data_directory.exists() and any(data_directory.iterdir()):
            raise SetupError("Refusing to initialize a nonempty local-data/postgres directory.")
        password_file = local_directory / "postgres-password"
        if not write_exclusive(password_file, values["POSTGRES_PASSWORD"] + "\n"):
            existing = password_file.read_text(encoding="utf-8").rstrip("\r\n")
            if not secrets.compare_digest(existing, values["POSTGRES_PASSWORD"]):
                raise SetupError("The existing native password file does not match .env.")
        print("Initializing project-local PostgreSQL data.")
        initialized = run_program(
            [
                str(initdb),
                "-D",
                str(data_directory),
                "--username",
                OWNER,
                "--pwfile",
                str(password_file),
                "--auth-host=scram-sha-256",
                "--auth-local=scram-sha-256",
                "--encoding=UTF8",
                "--locale=C",
            ]
        )
        if initialized.returncode:
            raise SetupError("PostgreSQL initialization failed; the data directory was preserved.")
    elif version_file.read_text(encoding="utf-8").strip() != "17":
        raise SetupError("The existing native data directory is not PostgreSQL 17.")

    status = run_program([str(pg_ctl), "-D", str(data_directory), "status"])
    if status.returncode == 0:
        print("Project-local PostgreSQL is already running.")
        return
    print("Starting project-local PostgreSQL.")
    started = run_program(
        [
            str(pg_ctl),
            "-D",
            str(data_directory),
            "-l",
            str(local_directory / "postgres.log"),
            "-o",
            f"-h 127.0.0.1 -p {PORT}",
            "-w",
            "-t",
            "30",
            "start",
        ],
        timeout=45,
    )
    if started.returncode:
        raise SetupError("PostgreSQL startup failed; inspect local-data/postgres.log.")


def connect(values: dict[str, str], username: str, database: str) -> psycopg.Connection[Any]:
    password_key = "POSTGRES_PASSWORD" if username == OWNER else "EXECBOUND_APP_PASSWORD"
    # Explicit local keyword arguments avoid service files and DSN query overrides.
    return psycopg.connect(
        host="127.0.0.1",
        hostaddr="127.0.0.1",
        port=PORT,
        user=username,
        password=values[password_key],
        dbname=database,
        connect_timeout=3,
        sslmode="disable",
        application_name="execbound_local_setup",
        options="-c search_path=pg_catalog -c statement_timeout=10000",
        autocommit=True,
    )


def validate_runtime(connection: psycopg.Connection[Any]) -> bool:
    record = connection.execute(
        "SELECT oid, rolcanlogin, rolsuper, rolcreatedb, rolcreaterole, rolinherit, "
        "rolreplication, rolbypassrls FROM pg_roles WHERE rolname = %s",
        (RUNTIME,),
    ).fetchone()
    if record is None:
        return False
    role_oid, *attributes = record
    if attributes != [True, False, False, False, False, False, False]:
        raise SetupError("The existing runtime role has unexpected attributes; it was not changed.")
    membership = connection.execute(
        "SELECT 1 FROM pg_auth_members WHERE member = %s LIMIT 1", (role_oid,)
    ).fetchone()
    if membership:
        raise SetupError("The existing runtime role has memberships; it was not changed.")
    ownership = connection.execute(
        "SELECT 1 FROM pg_shdepend WHERE refclassid = 'pg_authid'::regclass "
        "AND refobjid = %s AND deptype = 'o' LIMIT 1",
        (role_oid,),
    ).fetchone()
    if ownership:
        raise SetupError("The existing runtime role owns database objects; it was not changed.")
    return True


# The settings that make a cluster durable. A disposable one, a CI runner's own Compose
# database that the job removes at its end, turns all three off: then a checkpoint writes the
# dirty buffers to the operating system and syncs nothing. `DROP DATABASE` forces a checkpoint,
# so the suite's restricted-owner tests, which build and drop a database each, waited up to
# 762 s apiece for it on a CI runner whose disk was busy with other jobs. A crash of the database
# or the host can lose or corrupt a disposable cluster; nothing in it is kept.
DURABILITY = ("fsync", "full_page_writes", "synchronous_commit")


def set_durability(connection: psycopg.Connection[Any], *, durable: bool) -> None:
    """Make the cluster durable (PostgreSQL's defaults) or disposable, and wait until it is."""
    for name in DURABILITY:
        if durable:
            connection.execute(sql.SQL("ALTER SYSTEM RESET {}").format(sql.Identifier(name)))
        else:
            connection.execute(sql.SQL("ALTER SYSTEM SET {} = off").format(sql.Identifier(name)))
    connection.execute("SELECT pg_reload_conf()")
    wanted = "on" if durable else "off"
    deadline = time.monotonic() + 10
    while True:
        # A reload is asynchronous: each new statement reads the configuration it has by then.
        found = [connection.execute(f"SHOW {name}").fetchone() for name in DURABILITY]
        if all(row == (wanted,) for row in found):
            return
        if time.monotonic() >= deadline:
            raise SetupError("The database did not take its durability settings.")
        time.sleep(0.2)


def provision(
    values: dict[str, str],
    *,
    native: bool,
    test_workers: int = 0,
    disposable: bool = False,
) -> None:
    if type(test_workers) is not int or not 0 <= test_workers <= 64:
        raise SetupError("--test-workers must be between 0 and 64")
    databases = (*DATABASES, *(worker_database(f"gw{n}") for n in range(test_workers)))
    deadline = time.monotonic() + 35
    while True:
        try:
            connection = connect(values, OWNER, "postgres")
            break
        except psycopg.OperationalError as error:
            if time.monotonic() >= deadline:
                raise SetupError(
                    "Cannot authenticate to the expected local owner. Existing passwords "
                    "were not reset; verify the local instance and .env match."
                ) from error
            time.sleep(0.5)

    with connection:
        identity = connection.execute(
            "SELECT current_user, session_user, inet_server_port(), host(inet_server_addr())"
        ).fetchone()
        expected_port = PORT if native else 5432
        if (
            identity is None
            or identity[:3] != (OWNER, OWNER, expected_port)
            or (native and identity[3] != "127.0.0.1")
        ):
            raise SetupError("Refusing a database connection with an unexpected local identity.")
        # Reject an incompatible existing role before making any provisioning changes.
        role_exists = validate_runtime(connection)
        for database in DATABASES:
            existing = connection.execute(
                "SELECT pg_get_userbyid(datdba) FROM pg_database WHERE datname = %s",
                (database,),
            ).fetchone()
            if existing and existing[0] != OWNER:
                raise SetupError(
                    "An expected local database has another owner; it was not changed."
                )
        if role_exists:
            try:
                with connect(values, RUNTIME, "postgres"):
                    pass
            except psycopg.Error as error:
                raise SetupError(
                    "The existing runtime credential does not match .env; "
                    "its password was not reset."
                ) from error
        else:
            connection.execute(
                sql.SQL(
                    "CREATE ROLE {} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT "
                    "NOREPLICATION NOBYPASSRLS PASSWORD {}"
                ).format(sql.Identifier(RUNTIME), sql.Literal(values["EXECBOUND_APP_PASSWORD"]))
            )
            print("Created the restricted local runtime role.")
        for database in databases:
            if not connection.execute(
                "SELECT 1 FROM pg_database WHERE datname = %s", (database,)
            ).fetchone():
                connection.execute(
                    sql.SQL("CREATE DATABASE {} OWNER {}").format(
                        sql.Identifier(database), sql.Identifier(OWNER)
                    )
                )
                print(f"Created local database {database}.")
        # A native cluster is the developer's own and is left as it is. A Compose one is this
        # project's: disposable when asked, and otherwise durable again, so a cluster a
        # disposable run left behind does not stay that way.
        if not native:
            set_durability(connection, durable=not disposable)
            if disposable:
                print(
                    "Made the local database disposable: fsync, full-page writes and "
                    "synchronous commit are off."
                )

    for database in databases:
        with connect(values, RUNTIME, database) as connection:
            unexpected_creation = connection.execute(
                "SELECT has_database_privilege(current_user, current_database(), 'CREATE') "
                "OR EXISTS (SELECT 1 FROM pg_namespace "
                "WHERE has_schema_privilege(current_user, oid, 'CREATE') "
                "AND nspname NOT LIKE 'pg_temp_%' AND nspname NOT LIKE 'pg_toast_temp_%')"
            ).fetchone()
            if unexpected_creation != (False,):
                raise SetupError(
                    "The runtime has unexpected database/schema creation privileges; "
                    "no privileges were automatically changed."
                )
    print("Local PostgreSQL and both database credentials verified.")
    print("Migrations were not run. Next: uv run alembic upgrade head")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--postgres-bin",
        type=Path,
        help="Use native PostgreSQL 17 binaries instead of Docker Compose.",
    )
    parser.add_argument(
        "--compose-project",
        help="Docker Compose project name for the database (default: the compose file's).",
    )
    parser.add_argument(
        "--disposable",
        action="store_true",
        help=(
            "Turn off fsync, full-page writes and synchronous commit on the Compose database, "
            "for a database a CI job removes at its end: a crash can lose it. Without this a "
            "Compose database is made durable. Refused with --postgres-bin."
        ),
    )
    parser.add_argument(
        "--test-workers",
        type=int,
        default=0,
        help="Also create one test database per pytest-xdist worker (gw0 to gw(N-1)).",
    )
    arguments = parser.parse_args()
    if arguments.compose_project is not None and (
        arguments.postgres_bin is not None
        or not arguments.compose_project.replace("-", "").replace("_", "").isalnum()
    ):
        parser.error("--compose-project needs Docker Compose and a name of letters, digits, - or _")
    if arguments.disposable and arguments.postgres_bin is not None:
        parser.error("--disposable needs Docker Compose: a native cluster is not this project's")
    try:
        values = ensure_environment()
        if arguments.postgres_bin is None:
            start_docker(values, arguments.compose_project)
        else:
            start_native(arguments.postgres_bin, values)
        provision(
            values,
            native=arguments.postgres_bin is not None,
            test_workers=arguments.test_workers,
            disposable=arguments.disposable,
        )
    except SetupError as error:
        print(f"Local setup stopped: {error}", file=sys.stderr)
        return 1
    except (OSError, psycopg.Error) as error:
        # Driver errors can contain SQL literals and credentials. Do not print their text.
        print(
            f"Local setup stopped with {type(error).__name__}; no credentials printed.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
